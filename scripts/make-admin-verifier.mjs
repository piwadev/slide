#!/usr/bin/env node
// Derives the owner-only admin console verifier from the env var SLIDE_ADMIN_PASSPHRASE and writes js/core/adminVerifier.js.
// Only salt + PBKDF2-SHA256 hash + iteration count are written (never the passphrase). Run:  SLIDE_ADMIN_PASSPHRASE=... node scripts/make-admin-verifier.mjs
import { pbkdf2Sync, randomBytes } from 'node:crypto';
import { writeFileSync } from 'node:fs';
const pass = process.env.SLIDE_ADMIN_PASSPHRASE;
if (!pass) { console.error('SLIDE_ADMIN_PASSPHRASE is not set'); process.exit(1); }
const ITER = 310000, salt = randomBytes(16), hash = pbkdf2Sync(pass, salt, ITER, 32, 'sha256');
const out = `// Generated by scripts/make-admin-verifier.mjs - salt + PBKDF2-SHA256 hash only. The passphrase is never stored.\nexport const ADMIN_VERIFIER = { alg: 'PBKDF2-SHA256', iter: ${ITER}, salt: '${salt.toString('hex')}', hash: '${hash.toString('hex')}' };\n`;
writeFileSync(new URL('../js/core/adminVerifier.js', import.meta.url), out);
console.log('wrote js/core/adminVerifier.js (iterations ' + ITER + ')');
